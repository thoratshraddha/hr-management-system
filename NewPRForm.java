    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // Save
        String prno=txtprno.getText();
        if(txtprdate.getText().equals("")){
            Messages.showWarning("PR Date cannot be left empty", "Input Error");
            txtprdate.requestFocus();
            return;
        }
        String prdate=txtprdate.getDate().format(DateTimeFormatter.ISO_DATE);
        String suppno=txtno.getText();
        String suppname=txtname.getText();
        String total=txttotal.getText();
        //Apply Validation
        if(suppname.equals("")){
            Messages.showWarning("Supplier Name cannot be left empty", "Input Error");
            txtname.requestFocus();
            return;
        }
        if(total.equals("")){
            Messages.showWarning("Total Amt cannot be left empty", "Input Error");
            txttotal.requestFocus();
            return;
        }
        if(!Rules.isDouble(total)){
            Messages.showWarning("Total Amt should be in numeric format", "Input Error");
            txttotal.requestFocus();
            return;
        }
              
        String btntext=btnsave.getText();
        if(btntext.equals("Save")){
            db.execute("Insert into PR values(?,?,?,?,?)",prno,prdate,suppno,suppname,total);
            db.updateID("PRNo");
                for(int i=0;i<table1.getRowCount();i++){
                String prodno=table1.getValueAt(i, 0)+"";
                String pname=table1.getValueAt(i, 1)+"";
                String qty=table1.getValueAt(i, 2)+"";
                String price=table1.getValueAt(i, 3)+"";
                String unit=table1.getValueAt(i, 4)+"";
                String totalamt=table1.getValueAt(i, 5)+"";
                db.execute("Insert into PRItems values(?,?,?,?,?,?,?)",prno,prodno,pname,qty,price,unit,totalamt);
                //Update stock of each item
                db.execute("Update Product set Qty=Qty-? where ProdNo=?",qty,prodno);
            }
            db.execute("Update supplier set ACBalance=ACBalance-? where Suppno=?",total,suppno);
            Messages.showInfo("Purchase Return is created Successfully...", "Success");                
        }else{
            db.execute("Update PR set PRDate=?,SuppNo=?,Suppname=?,TotalAmt=? where PRNo=?",prdate,suppno,suppname,total,prno);
            try{
            //Restore Stock/Reverse enrty of stock
            ResultSet rs=db.getData("select * from PRItems where PRNo=?", prno);
            while(rs.next()){
                db.execute("update strock set qty=qty+? where ProdNo=?", rs.getString(4),rs.getString(2));
            }
            }catch(Exception ex){
                System.out.println("Error:  "+ex.getMessage());
            }
            //Delete all child entries from PRItems table
            db.execute("delete from PRItems where PRNo=?", prno);
            
            //Insert child entries from Table
            for(int i=0;i<table1.getRowCount();i++){
                String prodno=table1.getValueAt(i, 0)+"";
                String pname=table1.getValueAt(i, 1)+"";
                String qty=table1.getValueAt(i, 2)+"";
                String price=table1.getValueAt(i, 3)+"";
                String unit=table1.getValueAt(i, 4)+"";
                String totalamt=table1.getValueAt(i, 5)+"";
                db.execute("Insert into PRItems values(?,?,?,?,?,?,?)",prno,prodno,pname,qty,price,unit,totalamt);
                //Update stock of each item
                db.execute("Update Product set Qty=Qty-? where ProdNo=?",qty,prodno);
            }
            db.execute("Update supplier set ACBalance=ACBalance+? where Suppno=?",total,suppno);
            Messages.showInfo("Purchase Return is updated Successfully...", "Success");                
        }        
        db.fillTable(PRListForm.table1, "select * from PR");
        
    }//GEN-LAST:event_btnsaveActionPerformed

