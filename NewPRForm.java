    public void setPRInfo(String prno){
        try{
            ResultSet rs=db.getData("select * from PR where PRNo=?", prno);
            rs.next();
            txtprno.setText(rs.getString(1));
            txtprdate.setDate(LocalDate.parse(rs.getString(2)));
            txtno.setText(rs.getString(3));
            txtname.setText(rs.getString(4));
            txttotal.setText(rs.getString(5));
            oldtotal=txttotal.getText();
            db.fillTable(table1, "select ProdNo,ProductName,Qty,price,unit,total from PRItems where PRNo=?",prno);
            btnsave.setText("Update");
            lbltotal.setText("Total Items #"+table1.getRowCount());
            txtname.requestFocus();
        }catch(Exception ex){
            Messages.showError("Error: "+ex.getMessage(), "Error");
        }
    }

