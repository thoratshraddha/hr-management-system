    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // save
        String testno=txtno.getText();
        String appno=txtappno.getText();
        String present=txtpresent.getText();
        String marks=txtmarks.getText();
        String passfail=txtpassfail.getText();
        //Apply Validation
        if(appno.equals("")){
              Messages.showWarning("Test Name Cannot be left empty", "Input Error");
              txtappno.requestFocus();
              return;
          }
          if(present.equals("")){
              Messages.showWarning("Test Address cannot be empty", "Input Error");
              txtpresent.requestFocus();
              return;
          }
          if(marks.equals("")){
              Messages.showWarning("Mobile No cannot be left empty", "Input Error");
              txtmarks.requestFocus();
              return;
          }
          if(!Rules.isMobile(marks)){
              Messages.showWarning("Mobile no consist of only 10 digits", "Input Error");
              txtmarks.requestFocus();
              return;
          }
          if(passfail.equals("")){
              Messages.showWarning("Person Name cannot be left empty","Input Error");
              txtpassfail.requestFocus();
              return;
          }
          if(!Rules.isChars(passfail)){
              Messages.showWarning("Person Name allows only char and spaces", "Input Error");
              txtpassfail.requestFocus();
              return;
          }
          String btntext=btnsave.getText();//save Update
          if(btntext.equals("Save")){ //Insert
            db.execute("Insert into Test values(?,?,?,?,?)",testno,appno,present,marks,passfail);
            db.updateID("TestNo");
            Messages.showInfo("Test Information is Saved Successfully...", "Success");        
        }else{ //Update
            db.execute("Update Test set TestNo=? AppNo=?,PresentStatus=?,MarksObtained=?,Passfail=? where testno=?",appno,present,marks,passfail,testno);
            Messages.showInfo("Test Information is Updated Successfully...", "Success");        
        }
        db.fillTable(table1, "select * from Test");
        
    }//GEN-LAST:event_btnsaveActionPerformed

    private void btneditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneditActionPerformed
        //edit
        int i=table1.getSelectedRow();
        if(i!=-1){
            String testno=table1.getValueAt(i, 0)+"";
            String appno=table1.getValueAt(i, 1)+"";
            String present=table1.getValueAt(i, 2)+"";
            String marksno=table1.getValueAt(i, 3)+"";
            String contact=table1.getValueAt(i, 4)+"";
            txtno.setText(testno);
            txtappno.setText(appno);
            txtpresent.setText(present);
            txtmarks.setText(marksno);
            txtpassfail.setText(contact);
            btnsave.setText("Update");
            txtappno.requestFocus();            
        }else{
            Messages.showError("Please select row", "Row is Not Selected");
        }
    }//GEN-LAST:event_btneditActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        // delete
        int i=table1.getSelectedRow();
        if(i!=-1){
            int ans=Messages.showConfirm("Are you sure?", "Confirm Delete");
            if(ans==JOptionPane.YES_OPTION){
                String testno=table1.getValueAt(i, 0)+"";                
                db.execute("delete from Test where TestNo=?", testno);
                db.fillTable(table1, "SELECT * from Test");
            }
        }else{
            Messages.showError("Please select row to remove", "Row Not Selected");
        }
    }//GEN-LAST:event_btndeleteActionPerformed

