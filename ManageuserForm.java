    private void btnremoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnremoveActionPerformed
        // remove user
        int i=table1.getSelectedRow();
        if(i!=-1){
            String username=table1.getValueAt(i, 4)+"";
            if(username.equals("admin")){
                Messages.showError("You can not remove admin user...", "Invalid Operation");
                return;
            }
            int ans=Messages.showConfirm("Are you sure?", "Confirm User Delete");
           if(ans==JOptionPane.YES_OPTION){ 
            String userid=table1.getValueAt(i, 0)+"";
            db.execute("Delete from login where userid=?", userid);
            db.fillTable(table1, "SELECT UserId,Name,EmailId,MobileNo,UserName,sha(Password) as Password,SecQ,sha(seca) as SecA FROM login");
           }
        }else{
            Messages.showError("Please select user to remove", "user not selected");
        }
       
    }//GEN-LAST:event_btnremoveActionPerformed

