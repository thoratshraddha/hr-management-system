    private void btnsubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsubmitActionPerformed
        // submit
        String name=txtname.getText();
        String email=txtemail.getText();
        String mobile=txtmobile.getText();
        String user=txtuser.getText();
        String pass=txtpass.getText();
        String secq=cmbsecq.getSelectedItem()+"";
        String seca=txtseca.getText();
        db.execute("Insert into Login (Name,EmailId,MobileNo,UserName,Password,SecQ,SecA) values(?,?,?,?,?,?,?)",name,email,mobile,user,pass,secq,seca);
        Messages.showInfo("New User Created Successfully...", "New User");
        db.fillTable(table1, "SELECT UserId,Name,EmailId,MobileNo,UserName,sha(Password) as Password,SecQ,sha(seca) as SecA FROM login");
    }//GEN-LAST:event_btnsubmitActionPerformed

