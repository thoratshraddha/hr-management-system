    private void btnsubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsubmitActionPerformed
        // change password
        String oldpass=txtpass.getText();
        String newpass=txtpass1.getText();
        String cnewpass=txtpass2.getText();
        
        if(!oldpass.equals(StatusClass.pass)){
            Messages.showError("Old Password is wrong...try again", "Wrong Password");
            txtpass.requestFocus();
            return;
        }
        if(!newpass.equals(cnewpass)){
            Messages.showError("New Password Mismatch...try again", "Wrong Password");
            txtpass2.requestFocus();
            return;
        }
        db.execute("Update Login set Password=? where UserName=?",newpass,StatusClass.user);
        Messages.showInfo("Password changed successfully", "Success");
    }//GEN-LAST:event_btnsubmitActionPerformed

