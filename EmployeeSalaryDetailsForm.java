    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // save
        String empno=txtno.getText();
        if(txtsdate.getText().equals("")){
            Messages.showWarning("Agreement Date cannot be left empty", "Input Error");
            txtsdate.requestFocus();
            return;
        }
        String sdate=txtsdate.getDate().format(DateTimeFormatter.ISO_DATE);
        String month=txtmonth.getText();
        String year=txtyear.getText();
        String present=txttotalpresent.getText();
        String leave=txtleave.getText();
        String net=txtpay.getText();
        //Apply Validation
        if(month.equals("")){
              Messages.showWarning("Employee cannot be empty", "Input Error");
              txtmonth.requestFocus();
              return;
          }
          if(year.equals("")){
              Messages.showWarning("Year No cannot be left empty", "Input Error");
              txtyear.requestFocus();
              return;
          }
          if(!Rules.isChars(year)){
              Messages.showWarning("Mobile no consist of only 10 digits", "Input Error");
              txtyear.requestFocus();
              return;
          }
          if(present.equals("")){
              Messages.showWarning("Person Name cannot be left empty","Input Error");
              txttotalpresent.requestFocus();
              return;
          }
          if(!Rules.isChars(present)){
              Messages.showWarning("Person Name allows only char and spaces", "Input Error");
              txttotalpresent.requestFocus();
              return;
          }
          if(leave.equals("")){
              Messages.showWarning("Email Id is invalid", "Input Error");
              txtleave.requestFocus();
              return;
          }
          if(!Rules.isEmail(leave)){
              Messages.showWarning("Email Id is invalid", "Input Error");
              txtleave.requestFocus();
              return;
          }
          if(net.equals("")){
              Messages.showWarning("Web Site cannot be left empty", "Input Error");
              txtpay.requestFocus();
              return;
          }
          if(!Rules.isDouble(net)){
              Messages.showWarning("Web URL is invalid", "Input Error");
              txtpay.requestFocus();
              return;          
          }
          String btntext=btnsave.getText();//save Update
          if(btntext.equals("Save")){ //Insert
            db.execute("Insert into empsalarydetail values(?,?,?,?,?,?,?)",empno,sdate,month,year,present,leave,net);
            db.updateID("EmpNo");
            Messages.showInfo("empsalarydetail Information is Saved Successfully...", "Success");        
        }else{ //Update
            db.execute("Update empsalarydetail set sdate=?, month=?,year=?,totalpresent=?,totalleave=?,netpay=? where empno=?",sdate,month,year,present,leave,net,empno);
            Messages.showInfo("empsalarydetail Information is Updated Successfully...", "Success");        
        }
        db.fillTable(table1, "select * from empsalarydetail");
        
    }//GEN-LAST:event_btnsaveActionPerformed

