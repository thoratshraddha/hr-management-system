    private void btneditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneditActionPerformed
        // Edit
        int i=table1.getSelectedRow();
        if(i!=-1){
            String prodno=table1.getValueAt(i, 0)+"";
            String prodname=table1.getValueAt(i, 1)+"";
            String company=table1.getValueAt(i, 2)+"";
            String type=table1.getValueAt(i, 3)+"";
            String price=table1.getValueAt(i, 4)+"";
            String unit=table1.getValueAt(i, 5)+"";
            String qty=table1.getValueAt(i, 6)+"";
            
            txtno.setText(prodno);
            txtname.setText(prodname);
            cmbcompany.setSelectedItem(company);
            cmbtype.setSelectedItem(type);
            txtprice.setText(price);
            txtunit.setText(unit);
            txtqty.setText(qty);
            try{
            //Read Image from Table/DB
            ResultSet rs=db.getData("select ProductImage from Product where ProdNo=?", prodno);
            if(rs.next()){
                byte b[]=rs.getBytes(1);
                //write byte array to file
                //1 Create tenp file
                file=File.createTempFile("city", ".tmp");
                //It creates temp file in windows\temp folder
                //by name "city45hdh456556.tmp"
                FileUtils.writeByteArrayToFile(file, b);
                ImageUtility.setLabelImage(file, lblimg);
                
            }
            }catch(Exception ex){
                Messages.showError("Error: "+ex.getMessage(), "Error");
            }
            
            btnsave.setText("Update");
            txtname.requestFocus();            
        }else{
            Messages.showError("Please select row", "Row is Not Selected");
        }
        
    }//GEN-LAST:event_btneditActionPerformed

    private void btnedit1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnedit1ActionPerformed
        //Delete
        int i=table1.getSelectedRow();
        if(i!=-1){
            int ans=Messages.showConfirm("Are you sure?", "Confirm Delete");
            if(ans==JOptionPane.YES_OPTION){
                String suppno=table1.getValueAt(i, 0)+"";                
                db.execute("delete from Product where ProdNo=?", suppno);
                db.fillTable2(table1, "SELECT * from Product");
            }
        }else{
            Messages.showError("Please select row to remove", "Row Not Selected");
        }

    }//GEN-LAST:event_btnedit1ActionPerformed

