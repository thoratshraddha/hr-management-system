    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // Save
        String prodno=txtno.getText();
        String prodname=txtname.getText();
        String company=cmbcompany.getSelectedItem()+"";
        String type=cmbtype.getSelectedItem()+"";
        String price=txtprice.getText();
        String unit=txtunit.getText();
        String qty=txtqty.getText();
        //Apply Validation
        if(prodname.equals("")){
            Messages.showWarning("Product Name cannot be left empty", "Input Error");
            txtname.requestFocus();
            return;
        }
        if(price.equals("")){
            Messages.showWarning("Price cannot be left empty", "Input Error");
            txtprice.requestFocus();
            return;
        }
        if(!Rules.isDouble(price)){
            Messages.showWarning("Price should be in amount form", "Input Error");
            txtprice.requestFocus();
            return;
        }
        if(unit.equals("")){
            Messages.showWarning("Unit cannot be left empty", "Input Error");
            txtunit.requestFocus();
            return;
        }
        if(qty.equals("")){
            Messages.showWarning("Qty cannot be left empty", "Input Error");
            txtqty.requestFocus();
            return;
        }
        if(!Rules.isInteger(qty)){
            Messages.showWarning("Qty should be integer", "Input Error");
            txtqty.requestFocus();
            return;
        }
        String btntext=btnsave.getText(); //Save Update
        if(btntext.equals("Save")){ //Insert
            db.execute("Insert into Product values(?,?,?,?,?,?,?,?)",prodno,prodname,company,type,price,unit,qty,file);
            db.updateID("ProdNo");
                    
            Messages.showInfo("Product Information is Saved Successfully...", "Success");        
        }else{ //Update
            db.execute("Update Product set ProductName=?,Company=?,ProductType=?,Price=?,Unit=?,Qty=?,ProductImage=? where ProdNo=?",prodname,company,type,price,unit,qty,file,prodno);
            Messages.showInfo("Product Information is Updated Successfully...", "Success");        
        }
        db.fillTable2(table1, "select * from Product");
        
    }//GEN-LAST:event_btnsaveActionPerformed

