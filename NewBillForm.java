    public void setBillInfo(String billno){
        try{
            ResultSet rs=db.getData("select * from Bill where BillNo=?", billno);
            rs.next();
            txtbillno.setText(rs.getString(1));
            txtbilldate.setDate(LocalDate.parse(rs.getString(2)));
            cmbtype.setSelectedItem(rs.getString(3));
            txtcustno.setText(rs.getString(4));
            txtname.setText(rs.getString(5));
            txttotal.setText(rs.getString(6));
            txtdiscp.setText(rs.getString(7));
            txtdiscamt.setText(rs.getString(8));
            txtgstp.setText(rs.getString(9));
            txtgstamt.setText(rs.getString(10));
            txtnetamt.setText(rs.getString(11));
            db.fillTable(table1, "select ProdNo,ProductName,Qty,price,unit,total,discp,discamt,Net from BillItems where BillNo=?",billno);
            btnsave.setText("Update");
            lbltotal.setText("Total Items #"+table1.getRowCount());
            txtname.requestFocus();
        }catch(Exception ex){
            Messages.showError("Error: "+ex.getMessage(), "Error");
        }
    }

