    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        //Add Item
        String pid=txtprodno.getText();
        String pname=txtpname.getText();
        String qty=txtqty.getText();
        String price=txtprice.getText();
        String unit=txtunit.getText();
        double total=Integer.parseInt(qty)*Double.parseDouble(price);
        String discp=txtdiscp1.getText();
        if(discp.equals("")){
            discp="0";
        }
        double discamt=total*(Double.parseDouble(discp)/100);
        double net=total-discamt;              
        DefaultTableModel dt= (DefaultTableModel) table1.getModel();
        Object obj[]={pid,pname,qty,price,unit,total,discp,discamt,net};
        dt.addRow(obj);
        lbltotal.setText("Total Items #"+dt.getRowCount());
        getTotal();
        btnprod.requestFocus();
    }//GEN-LAST:event_btnaddActionPerformed
  void getTotal(){
       double total=0;
        for(int i=0;i<table1.getRowCount();i++){
            total+= Double.parseDouble(table1.getValueAt(i, 8)+"");
        }
        DecimalFormat df=new DecimalFormat("0.00");
        //format method==> formats given double no and returns string
        txttotal.setText(df.format(total));
        String discp=txtdiscp.getText();//5 1 10 6
        if(discp.equals("")){
            discp="0";
        }
        String gsttax=txtgstp.getText();
        if(gsttax.equals("")){
            gsttax="0";
        }
        double discamt=total*(Double.parseDouble(discp)/100);
        total=total-discamt;
        double gstamt=total*(Double.parseDouble(gsttax)/100);
        total=total+gstamt;
        
        //txtdiscp.setText(discp);
        txtdiscamt.setText(df.format(discamt));
        //txtgstp.setText(gsttax);
        txtgstamt.setText(df.format(gstamt));
        txtnetamt.setText(df.format(total));
  }
