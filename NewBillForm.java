    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
       // Save
        String billno=txtbillno.getText();
        if(txtbilldate.getText().equals("")){
            Messages.showWarning("Bill Date cannot be left empty", "Input Error");
            txtbilldate.requestFocus();
            return;
        }
        String type=cmbtype.getSelectedItem()+"";
        String billdate=txtbilldate.getDate().format(DateTimeFormatter.ISO_DATE);
        String custno=txtcustno.getText();
        String custname=txtname.getText();
        String total=txttotal.getText();
        String discp=txtdiscp.getText();
        String discamt=txtdiscamt.getText();
        String gstp=txtgstp.getText();
        String gstamt=txtgstamt.getText();
        String netamt=txtnetamt.getText();
        
        //Apply Validation
        if(custname.equals("")){
            Messages.showWarning("Customer Name cannot be left empty", "Input Error");
            txtname.requestFocus();
            return;
        }
        if(total.equals("")){
            Messages.showWarning("Total Amt cannot be left empty", "Input Error");
            txttotal.requestFocus();
            return;
        }
        if(!Rules.isDouble(total)){
            Messages.showWarning("Total Amt should be in numeric format", "Input Error");
            txttotal.requestFocus();
            return;
        }
        if(discp.equals("")){
            Messages.showWarning("Discount Percent cannot be left empty", "Input Error");
            txtdiscp.requestFocus();
            return;
        }
        if(!Rules.isDouble(discp)){
            Messages.showWarning("Total Amt should be in numeric format", "Input Error");
            txttotal.requestFocus();
            return;
        }
        if(gstp.equals("")){
            Messages.showWarning("GST Tax Percent cannot be left empty", "Input Error");
            txtgstp.requestFocus();
            return;
        }
        if(!Rules.isDouble(gstamt)){
            Messages.showWarning("GST Amt should be in numeric format", "Input Error");
            txtgstamt.requestFocus();
            return;
        }
        if(netamt.equals("")){
            Messages.showWarning("Bet Amount cannot be left empty", "Input Error");
            txtnetamt.requestFocus();
            return;
        }
        if(!Rules.isDouble(netamt)){
            Messages.showWarning("Net Amt should be in numeric format", "Input Error");
            txtnetamt.requestFocus();
            return;
        }
        
        String btntext=btnsave.getText();
        if(btntext.equals("Save")){
            db.execute("Insert into Bill values(?,?,?,?,?,?,?,?,?,?,?)",billno,billdate,type,custno,custname,total,discp,discamt,gstp,gstamt,netamt);
            db.updateID("BillNo");
        
            for(int i=0;i<table1.getRowCount();i++){
                String prodno=table1.getValueAt(i, 0)+"";
                String pname=table1.getValueAt(i, 1)+"";
                String qty=table1.getValueAt(i, 2)+"";
                String price=table1.getValueAt(i, 3)+"";
                String unit=table1.getValueAt(i, 4)+"";
                String totalamt=table1.getValueAt(i, 5)+"";
                String discp1=table1.getValueAt(i, 6)+"";
                String discamt1=table1.getValueAt(i, 7)+"";
                String netamt1=table1.getValueAt(i, 8)+"";
                db.execute("Insert into BillItems values(?,?,?,?,?,?,?,?,?,?)",billno,prodno,pname,qty,price,unit,totalamt,discp1,discamt1,netamt1);
                //Update stock of each item
                db.execute("Update Product set Qty=Qty-? where ProdNo=?",qty,prodno);
            }
            if(type.equals("CREDIT"))
            db.execute("Update Customer Set ACBalance=ACBalance+? where CustNo=?", netamt,custno);
            Messages.showInfo("Bill is created Successfully...", "Success");                
        }else{
            db.execute("Update Bill set BillDate=?,TransType=?,CustNo=?,Custname=?,TotalAmt=?,Discp=?,Discamt=?,gst=?,GStamt=?,NetAmt=? where BillNo=?",billdate,type,custno,custname,total,discp,discamt,gstp,gstamt,netamt,billno);
            try{
            //Restore Stock/Reverse enrty of stock
            ResultSet rs=db.getData("select * from BillItems where BillNo=?", billno);
            while(rs.next()){
                db.execute("update product set qty=qty-? where ProdNo=?", rs.getString(4),rs.getString(2));
            }
            }catch(Exception ex){
                System.out.println("Error:  "+ex.getMessage());
            }
            //Delete all child entries from BillItems table
            db.execute("delete from BillItems where BillNo=?", billno);
            
            //Insert child entries from Table
            for(int i=0;i<table1.getRowCount();i++){
                String prodno=table1.getValueAt(i, 0)+"";
                String pname=table1.getValueAt(i, 1)+"";
                String qty=table1.getValueAt(i, 2)+"";
                String price=table1.getValueAt(i, 3)+"";
                String unit=table1.getValueAt(i, 4)+"";
                String totalamt=table1.getValueAt(i, 5)+"";
                String discp1=table1.getValueAt(i, 6)+"";
                String discamt1=table1.getValueAt(i, 7)+"";
                String netamt1=table1.getValueAt(i, 8)+"";
                db.execute("Insert into BillItems values(?,?,?,?,?,?,?,?,?,?)",billno,prodno,pname,qty,price,unit,totalamt,discp1,discamt1,netamt1);
                //Update stock of each item
                db.execute("Update Product set Qty=Qty+? where ProdNo=?",qty,prodno);
            }
            Messages.showInfo("Bill is updated Successfully...", "Success");                
        }        
        db.fillTable(BillListForm.table1, "select * from Bill");
        
    }//GEN-LAST:event_btnsaveActionPerformed

