    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // save
        String EmpAttNo=txtno.getText();
       String date=txtdate.getText();
        if(txtdate.getText().equals("")){
            Messages.showWarning("MR Date cannot be left empty", "Input Error");
            txtdate.requestFocus();
            return;
        }
        String intime=txtintime.getText();
        String outtime=txtouttime.getText();
        String remark=txtremark.getText();
        //Apply Validation
        if(txtdate.equals("")){
              Messages.showWarning("Today date Cannot be left empty", "Input Error");
              txtdate.requestFocus();
              return;
          }
          if(intime.equals("")){
              Messages.showWarning("Supplier Address cannot be empty", "Input Error");
              txtintime.requestFocus();
              return;
          }
          if(outtime.equals("")){
              Messages.showWarning("Mobile No cannot be left empty", "Input Error");
              txtouttime.requestFocus();
              return;
          }
          if(!Rules.isMobile(outtime)){
              Messages.showWarning("Mobile no consist of only 10 digits", "Input Error");
              txtouttime.requestFocus();
              return;
          }
          if(remark.equals("")){
              Messages.showWarning("Person Name cannot be left empty","Input Error");
              txtremark.requestFocus();
              return;
          }
          if(!Rules.isChars(remark)){
              Messages.showWarning("Person Name allows only char and spaces", "Input Error");
              txtremark.requestFocus();
              return;
          }
          String btntext=btnsave.getText();//save Update
          if(btntext.equals("Save")){ //Insert
            db.execute("Insert into empattendance values(?,?,?,?,?,?,?,?)",EmpAttNo,date,intime,outtime,remark);
            db.updateID("EmpAttNo");
            Messages.showInfo("employee Information is Saved Successfully...", "Success");        
        }else{ //Update
            db.execute("Update empattandance set Todaydate=?,Intime=?,OutTime=?,Remark=?where EmpAttNo=?",date,intime,outtime,remark,EmpAttNo);
            Messages.showInfo("employee Information is Updated Successfully...", "Success");        
        }
        db.fillTable(table1, "select * from empAttandance");
        
    }//GEN-LAST:event_btnsaveActionPerformed

    private void btneditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneditActionPerformed
        //edit
        int i=table1.getSelectedRow();
        if(i!=-1){
            String EmpAttNo=table1.getValueAt(i, 0)+"";
            String date=table1.getValueAt(i, 1)+"";
            String intime=table1.getValueAt(i, 2)+"";
            String outtime=table1.getValueAt(i, 3)+"";
            String remark=table1.getValueAt(i, 4)+"";
            txtno.setText(EmpAttNo);
            txtdate.setText(date);
            txtintime.setText(intime);
            txtouttime.setText(outtime);
            txtremark.setText(remark);
            txtdate.requestFocus();
        }else{
            Messages.showError("Please select row", "Row is Not Selected");
        }
    }//GEN-LAST:event_btneditActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        // delete
        int i=table1.getSelectedRow();
        if(i!=-1){
            int ans=Messages.showConfirm("Are you sure?", "Confirm Delete");
            if(ans==JOptionPane.YES_OPTION){
                String EmpAttNo=table1.getValueAt(i, 0)+"";                
                db.execute("delete from EmpAttandance where EmpAttNo=?", EmpAttNo);
                db.fillTable(table1, "SELECT * from empattandance");
            }
        }else{
            Messages.showError("Please select row to remove", "Row Not Selected");
        }
    }//GEN-LAST:event_btndeleteActionPerformed

